def tab_exp7_matrix() -> None:
    df = data(7)
    d11 = data(11)
    ks = [int(k) for k in cfg()["exp7_batch_counts"]]
    algos = [PAPER_UB, "EHAUSM-I", "Pre-HAUSPM"]
