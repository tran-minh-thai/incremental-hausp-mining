def tab_variance() -> None:
    rows = []
    frames = []
    for exp in (1, 2, 3, 4, 8):
        df = data(exp)
        if df is None:
            continue
        frames.append(df)
        ok = df[df["Status"].isin(OK)]
        keys = ["Dataset", "Algorithm", "MinUtil", "DeltaRatio"]
        per = ok.groupby(keys + ["RunIndex"], as_index=False).agg(t=("tTotal(ms)", "sum"))
        g = per.groupby(keys)["t"]
        cv = (g.std() / g.mean()).dropna() * 100
        ntr = g.count()
        big = cv[g.mean()[cv.index] >= 5000]
        rows.append((f"Exp.~{exp}", len(cv), f"{ntr.min()}--{ntr.max()}" if ntr.min() != ntr.max() else str(ntr.min()),
                     cv.median(), cv.quantile(0.95), big.max() if len(big) else float("nan")))
    df7 = data(7)
    if df7 is not None:
        frames.append(df7)
        ok7 = df7[df7["Status"].isin(OK)].copy()
        ok7["K"] = (1.0 / ok7["DeltaRatio"]).round().astype(int)
        per7 = ok7.groupby(["Dataset", "Algorithm", "K", "RunIndex"], as_index=False).agg(n=("BatchID", "count"), t=("tTotal(ms)", "sum"))
        per7 = per7[per7["n"] == per7["K"]]
        tri = per7.groupby(["Dataset", "Algorithm", "K"])["RunIndex"].nunique()
        full = per7.set_index(["Dataset", "Algorithm", "K"]).loc[tri[tri >= 3].index].reset_index()
        g7 = full.groupby(["Dataset", "Algorithm", "K"])["t"]
        cv7 = (g7.std() / g7.mean()).dropna() * 100
        n7 = g7.count()
        big7 = cv7[g7.mean()[cv7.index] >= 5000]
        rows.append(("Exp.~7", len(cv7), f"{n7.min()}--{n7.max()}" if len(n7) and n7.min() != n7.max() else (str(n7.min()) if len(n7) else "--"),
                     cv7.median(), cv7.quantile(0.95), big7.max() if len(big7) else float("nan")))
    lines = table_head(
        r"Run-to-run variability of total runtime: CV = std/mean per configuration; trials per configuration"
        r" (3 by default, 10 for configurations under 10\,s and 15 under 1\,s); last column: configurations with mean runtime at least 5\,s.",
        r"\label{tab:variance}", "lrrrrr",
        r"Experiment & Configs & Trials & Median CV (\%) & 95th pct.\ CV (\%) & Max CV (\%), runs $\geq$ 5\,s \\")
    for name, n, tr, med, p95, mx in rows:
        mxs = f"{mx:.1f}" if np.isfinite(mx) else "--"
        lines.append(f"{name} & {n} & {tr} & {med:.2f} & {p95:.2f} & {mxs} \\\\")
    lines += table_tail()
    emit("tab_variance.tex", "tab:variance", lines, frames)


def tab_datasets() -> None:
    stats_p = ANALYSIS_OUT / "dataset_stats.json"
    if not stats_p.exists():
        raise SystemExit("analysis_out/paper/dataset_stats.json missing: run analysis/dataset_stats.py first")
    stats = json.loads(stats_p.read_text())
    exp2 = next(e for e in cfg()["experiments"] if e["id"] == 2)
    sweeps = {r["csv_name"]: r["min_utils"] for r in exp2["runs"]}
    order = sorted([d for d in DS_ORDER if d in stats], key=lambda d: stats[d]["sequences"])
    lines = table_head(
        r"Statistical characteristics of the experimental datasets (measured from the files: sequences $|D|$,"
        r" distinct items $|I|$, mean itemsets per sequence, total utility) and the per-dataset $minUtil$ sweep of Experiment~2.",
        r"\label{tab:datasets}\label{tab:exp2_params}", "lrrrrl",
        r"Dataset & $|D|$ & $|I|$ & Avg.\ itemsets/seq.\ & Total utility & $minUtil$ sweep (\%) \\")
    for d in order:
        s = stats[d]
        sw = ";\; ".join(f"{v*100:.3f}".rstrip("0").rstrip(".") for v in sweeps.get(d, []))
        lines.append(f"{ds_tex(d)} & {thousands(s['sequences'])} & {thousands(s['items'])} & {s['avg_itemsets']:.2f} & "
                     f"{thousands(s['total_utility'])} & {sw} \\\\")
    lines += table_tail()
    # datasets table has no CSV source; record the stats file and the config dump instead
    fake = pd.DataFrame(); fake.attrs["source"] = "analysis_out/paper/dataset_stats.json;analysis_out/paper/experiment_config.json"
    fake.attrs["run_ids"] = ["measured-from-files"]
    emit("tab_datasets.tex", "tab:datasets", lines, [fake])


def tab_exp1_eta_avg() -> None:
    df = data(1)
    ok = df[df["Status"].isin(OK)].copy()
    ok = ok[ok["RunIndex"] == ok.groupby(["Dataset", "Algorithm"])["RunIndex"].transform("min")]
    ok["eta"] = ok["CandUnified"] / ok["HAUSP"].replace(0, np.nan)
    m = ok.groupby(["Dataset", "Algorithm"])["eta"].mean().unstack("Algorithm")
    lines = table_head(
        r"Mean candidate-generation efficiency $\eta = $ lists assembled$/|\mathit{HAUSP}|$ over five batches"
        r" (the same operational count for every algorithm) and the ratio $\eta(\text{EHAUSM-R})/\eta(\text{HAUSP-UB})$.",
        r"\label{tab:exp1_eta_avg}", "lrrrr",
        r"Dataset & $\eta$ EHAUSM-I & $\eta$ EHAUSM-R & $\eta$ HAUSP-UB & Ratio \\")

    for ds in DS_ORDER:
        if ds not in m.index:
            continue
        r_ = m.loc[ds]
        cells = [(r_.get(a, np.nan), fmt_eta(r_.get(a, np.nan))) for a in ["EHAUSM-I", "EHAUSM-R", PAPER_UB]]
        ub = r_.get(PAPER_UB, np.nan)
        ratio = r_["EHAUSM-R"] / ub if (np.isfinite(ub) and ub) else np.nan
        ratio_s = ("$" + fmt_sig(ratio, 3) + r"\times$") if np.isfinite(ratio) else "--"
        lines.append(ds_tex(ds) + " & " + " & ".join(bold_best(cells)) + " & " + ratio_s + r" \\")
    lines += table_tail()
    emit("tab_exp1_eta_avg.tex", "tab:exp1_eta_avg", lines, [df])


def tab_phase_breakdown() -> None:
    # Batch-level timers only (scan+flatten, mining, Layer-1 filter). The per-node Layer-2/3
    # timers were removed from the hot path on 2026-09-10: a thread CPU-time read costs more
    # than the comparison it brackets, so their columns measured the timers, not the filters.
    df = data(1)
    ok = df[df["Status"].isin(OK) & (df["Algorithm"] == PAPER_UB)]
    per = ok.groupby(["Dataset", "RunIndex"], as_index=False)[["tScan(ms)", "tMining(ms)", "tLayer1(ms)", "tTotal(ms)"]].sum()
    for c in ["tScan(ms)", "tMining(ms)", "tLayer1(ms)"]:
        per[c] = 100.0 * per[c] / per["tTotal(ms)"]
    m = per.groupby("Dataset").mean(numeric_only=True)
    lines = table_head(
        r"Phase-level runtime breakdown of HAUSP-UB (\% of total runtime over five batches, mean over trials; "
        r"batch-level timers only: the Layer-2 and Layer-3 tests are single comparisons per child and are "
        r"characterised by the counts of Table~\ref{tab:exp9_counts}, not timed).",
        r"\label{tab:phase_breakdown}", "lrrr",
        r"Dataset & Scan+flatten & Mining & L1 filter \\")
    for ds in DS_ORDER:
        if ds not in m.index:
            continue
        r_ = m.loc[ds]
        lines.append(f"{ds_tex(ds)} & {pct(r_['tScan(ms)'])} & {pct(r_['tMining(ms)'])} & {pct(r_['tLayer1(ms)'])} \\\\")
    lines += table_tail()
    emit("tab_phase_breakdown.tex", "tab:phase_breakdown", lines, [df])


def runtime_cell(g: pd.DataFrame, n_batches: int, scale: float, nd: int) -> tuple[float | None, str]:
    trials = complete_trials(g, n_batches)
    if trials:
        succ = g[g["Status"].isin(OK)]
        per = [succ[succ["RunIndex"] == r]["tTotal(ms)"].sum() / scale for r in trials]
        return float(np.mean(per)), (ms_std(per, nd=nd) if len(per) >= 3 else f"{per[0]:.{nd}f}$^{{\\dagger}}$")
    fc = fail_cell(g)
    return None, (fc if fc else "--")


