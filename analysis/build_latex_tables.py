#!/usr/bin/env python3
"""Generate paper-ready LaTeX tables directly from results/exp*/ CSVs.

Every number in the revised manuscript's tables comes from this script — no
hand transcription. Output: analysis_out/paper/latex/*.tex
Usage: python3 analysis/build_latex_tables.py
"""
from __future__ import annotations

from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"
OUT = ROOT / "analysis_out" / "paper" / "latex"
OUT.mkdir(parents=True, exist_ok=True)

DS_ORDER = ["BIBLE", "BMS1_SPMF", "FIFA", "KOSARAK", "LEVIATHAN", "SIGN", "C8T1S5I8N5K"]
DS_TEX = {"BMS1_SPMF": "BMS1", "C8T1S5I8N5K": "SYN"}
ALGO_ORDER = ["EHAUSM-R", "EHAUSM-I", "Pre-HAUSPM", "HAUSP-UB-L1", "HAUSP-UB"]
OK = {"SUCCESS", "SUCCESS_MATCH"}
RULE_MS = 60 * 60000


def load(path: str) -> pd.DataFrame:
    df = pd.read_csv(R / path)
    df.columns = [c.strip() for c in df.columns]
    return df


def ds_tex(ds: str) -> str:
    return DS_TEX.get(ds, ds)


def emit(name: str, lines: list[str]) -> None:
    p = OUT / name
    p.write_text("\n".join(lines) + "\n")
    print(f"  [latex] {p.relative_to(ROOT)}")


def ms_std(vals, scale=1.0, nd=1):
    m, s = np.mean(vals) / scale, (np.std(vals, ddof=1) / scale if len(vals) > 1 else 0.0)
    if s < 0.5 * 10 ** (-nd):  # std rounds to zero at this precision -> omit
        return f"{m:.{nd}f}"
    return f"{m:.{nd}f} $\\pm$ {s:.{nd}f}"


def human(v) -> str:
    """Compact count: 951 -> 951; 36,287 -> 36.3K; 286,090,251 -> 286.1M."""
    v = float(v)
    for cut, suf in ((1e9, "B"), (1e6, "M"), (1e3, "K")):
        if abs(v) >= cut:
            return f"{v / cut:.1f}{suf}"
    return f"{v:.0f}"


# ------------------------------------------------------------- exp7 matrix
def exp7_matrix() -> None:
    df = load("exp7/experiment7_long_batch.csv")
    df["K"] = (1.0 / df["DeltaRatio"]).round().astype(int)
    lines = [
        "% Auto-generated by analysis/build_latex_tables.py — do not edit numbers by hand.",
        "\\begin{table}[!ht]",
        "\\centering",
        "\\small",
        "\\renewcommand{\\arraystretch}{1.15}",
        "\\caption{Experiment 7 --- total runtime (minutes, mean $\\pm$ std over three trials)"
        " for $K$ consecutive batches of equal size with the total data volume held fixed."
        " Every algorithm attempts the identical schedule $K\\in\\{10,20,50,100\\}$ under the"
        " same 90-minute per-batch limit and 24\\,GB heap. OT@$b$ / OOM@$b$: the run exceeded"
        " the time limit / memory at batch index $b$ (completed batches are retained);"
        " $\\dagger$: single trial (uniform rule: repeat trials are executed only when the"
        " first trial finishes within 60 minutes). The $\\pm$ term is omitted"" when the std rounds to zero at the displayed precision.}",
        "\\label{tab:exp7_matrix}",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Dataset & Algorithm & $K{=}10$ & $K{=}20$ & $K{=}50$ & $K{=}100$ \\\\",
        "\\midrule",
    ]
    for ds in DS_ORDER:
        first = True
        for algo in ["HAUSP-UB", "EHAUSM-I", "Pre-HAUSPM"]:
            cells = []
            for k in [10, 20, 50, 100]:
                g = df[(df.Dataset == ds) & (df.Algorithm == algo) & (df.K == k)]
                succ = g[g.Status == "SUCCESS"]
                trials = [r for r in sorted(succ.RunIndex.unique())
                          if len(succ[succ.RunIndex == r]) == k]
                fails = g[g.Status.isin(["OT", "OOM"])]
                if len(fails) and not trials:
                    f0 = fails.iloc[0]
                    cells.append(f"{f0.Status}@{int(f0.BatchID)}")
                elif trials:
                    per = [succ[succ.RunIndex == r]["tTotal(ms)"].sum() / 60000.0 for r in trials]
                    if len(per) >= 3:
                        cells.append(ms_std(per, nd=1))
                    else:
                        cells.append(f"{per[0]:.1f}$^{{\\dagger}}$")
                else:
                    cells.append("--")
            head = ds_tex(ds) if first else ""
            lines.append(f"{head} & {algo} & " + " & ".join(cells) + " \\\\")
            first = False
        lines.append("\\addlinespace")
    if lines[-1] == "\\addlinespace":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    emit("tab_exp7_matrix.tex", lines)


