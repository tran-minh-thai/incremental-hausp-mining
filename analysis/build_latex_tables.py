# ------------------------------------------------------------- exp8 eta
def exp8_eta() -> None:
    df = load("exp8/experiment8_threshold_sensitivity.csv")
    ok = df[df.Status.isin(OK)].copy()
    ok["eta"] = ok["Cand"] / ok["HAUSP"].replace(0, np.nan)
    lines = [
        "% Auto-generated by analysis/build_latex_tables.py",
        "\\begin{table}[!ht]",
        "\\centering",
        "\\small",
        "\\renewcommand{\\arraystretch}{1.15}",
        "\\caption{Experiment 8 --- candidate-generation efficiency"
        " $\\eta = |\\mathit{Cand}|/|\\mathit{HAUSP}|$ (lower is tighter) as"
        " \\textit{minUtil} approaches each dataset's noise floor;"
        " $|\\mathit{HAUSP}|$ is the number of patterns at that threshold."
        " Counts are deterministic across trials; $|\\mathit{HAUSP}|$ and the"" baseline's $\\eta$ use compact units (K/M).}",
        "\\label{tab:exp8_eta}",
        "\\begin{tabular}{lrrrrr}",
        "\\toprule",
        "Dataset & \\textit{minUtil} (\\%) & $|\\mathit{HAUSP}|$ & $\\eta$ EHAUSM-I & $\\eta$ HAUSP-UB & ratio \\\\",
        "\\midrule",
    ]
    for ds in DS_ORDER:
        sub = ok[ok.Dataset == ds]
        first = True
        for mu in sorted(sub.MinUtil.unique(), reverse=True):
            r = sub[sub.MinUtil == mu]
            e_i = r[r.Algorithm == "EHAUSM-I"]["eta"].mean()
            e_u = r[r.Algorithm == "HAUSP-UB"]["eta"].mean()
            h = int(r[r.Algorithm == "HAUSP-UB"]["HAUSP"].iloc[0])
            ratio = e_i / e_u if e_u and np.isfinite(e_i) else np.nan
            head = ds_tex(ds) if first else ""
            mu_pct = f"{mu*100:.3f}".rstrip("0").rstrip(".")
            eu = f"{e_u:,.1f}".replace(",", "\\,")
            rt = f"{ratio:,.0f}".replace(",", "{,}")
            lines.append(head + " & " + mu_pct + " & " + human(h) + " & "
                         + human(e_i) + " & " + eu + " & " + rt + "$\\times$ \\\\")
            first = False
        lines.append("\\addlinespace")
    if lines[-1] == "\\addlinespace":
        lines.pop()
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    emit("tab_exp8_eta.tex", lines)


# ------------------------------------------------------------- variance
def variance() -> None:
    rows = []
    for exp, path in ((1, "exp1/experiment1_tightness.csv"),
                      (2, "exp2/experiment2_pruning_power.csv"),
                      (3, "exp3/experiment3_scalability.csv"),
                      (4, "exp4/experiment4_memory_prelarge.csv"),
                      (8, "exp8/experiment8_threshold_sensitivity.csv")):
        df = load(path)
        ok = df[df.Status.isin(OK)]
        keys = ["Dataset", "Algorithm", "MinUtil", "DeltaRatio"]
        per = ok.groupby(keys + ["RunIndex"], as_index=False).agg(t=("tTotal(ms)", "sum"))
        g = per.groupby(keys)["t"]
        cv = (g.std() / g.mean()).dropna() * 100
        big = cv[g.mean()[cv.index] >= 5000]
        rows.append((f"Exp.~{exp}", len(cv), cv.median(), cv.quantile(0.95),
                     big.max() if len(big) else float("nan")))
    df7 = load("exp7/experiment7_long_batch.csv")
    ok7 = df7[df7.Status.isin(OK)].copy()
    ok7["K"] = (1.0 / ok7["DeltaRatio"]).round().astype(int)
    per7 = ok7.groupby(["Dataset", "Algorithm", "K", "RunIndex"], as_index=False).agg(
        n=("BatchID", "count"), t=("tTotal(ms)", "sum"))
    tri = per7.groupby(["Dataset", "Algorithm", "K"])["RunIndex"].nunique()
    full = per7.set_index(["Dataset", "Algorithm", "K"]).loc[tri[tri == 3].index].reset_index()
    g7 = full.groupby(["Dataset", "Algorithm", "K"])["t"]
    cv7 = (g7.std() / g7.mean()).dropna() * 100
    big7 = cv7[g7.mean()[cv7.index] >= 5000]
    rows.append(("Exp.~7", len(cv7), cv7.median(), cv7.quantile(0.95),
                 big7.max() if len(big7) else float("nan")))
    lines = [
        "% Auto-generated by analysis/build_latex_tables.py",
        "\\begin{table}[!ht]",
        "\\centering",
        "\\small",
        "\\renewcommand{\\arraystretch}{1.15}",
        "\\caption{Run-to-run variability of total runtime over three independent trials:"
        " coefficient of variation (CV = std/mean) per configuration. The last column"
        " restricts to configurations whose mean runtime is at least 5\\,s, where relative"
        " noise is meaningful. Candidate and pattern counts are fully deterministic"
        " (zero variance) in every experiment.}",
        "\\label{tab:variance}",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "Experiment & Configs & Median CV (\\%) & 95th pct.\\ CV (\\%) & Max CV (\\%), runs $\\geq$ 5\\,s \\\\",
        "\\midrule",
    ]
    for name, n, med, p95, mx in rows:
        mxs = f"{mx:.1f}" if np.isfinite(mx) else "--"
        lines.append(f"{name} & {n} & {med:.2f} & {p95:.2f} & {mxs} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    emit("tab_variance.tex", lines)




