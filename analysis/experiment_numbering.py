#!/usr/bin/env python3
"""Write the table that joins campaign experiment numbers to the manuscript's, into the README.

The campaign numbers (results/expN, launcher --exp N) identify runs and artefacts and never change;
the manuscript numbers its experiments by the order of its argument. analysis/paper_experiment_numbers.json
holds the mapping. This script renders it into the README block between the markers below, so the
README cannot drift from the file the table generators read. Both modes first refuse a mapping
that leaves a results/expN directory unnumbered, maps a campaign that has no directory, skips a
manuscript number, or gives a manuscript number only to studies inside another section.

    python3 analysis/experiment_numbering.py           # rewrite the README block
    python3 analysis/experiment_numbering.py --check   # exit 1 when the README block differs
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "analysis" / "paper_experiment_numbers.json"
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN experiment-numbering (generated by analysis/experiment_numbering.py) -->"
END = "<!-- END experiment-numbering -->"


def problems(m: dict) -> list[str]:
    """What makes the mapping unusable: a campaign without a manuscript number, a gap in the
    manuscript numbering, or a manuscript number carried only by studies inside another section."""
    out = []
    on_disk = {p.name[3:] for p in (ROOT / "results").glob("exp*") if p.is_dir() and p.name[3:].isdigit()}
    for k in sorted(on_disk - set(m), key=int):
        out.append(f"results/exp{k} has no manuscript number in {MAP.name}")
    for k in sorted(set(m) - on_disk, key=int):
        out.append(f"{MAP.name} maps campaign {k}, but results/exp{k} does not exist")
    nums = sorted({e["manuscript"] for e in m.values()})
    if nums != list(range(1, len(nums) + 1)):
        out.append(f"manuscript numbers {nums} are not consecutive from 1")
    for n in nums:
        if all(e.get("role") for e in m.values() if e["manuscript"] == n):
            out.append(f"manuscript Experiment {n} has only studies with a role, no campaign of its own")
    return out


def block() -> str:
    m = json.loads(MAP.read_text(encoding="utf-8"))["experiments"]
    bad = problems(m)
    if bad:
        raise SystemExit("experiment_numbering: " + "; ".join(bad))
    lines = [BEGIN, "",
             "| Campaign (`results/expN`, `--exp N`) | Manuscript | Measures |",
             "|---|---|---|"]
    for k in sorted(m, key=int):
        e = m[k]
        where = f"Experiment {e['manuscript']}" + (f" ({e['role']}, no number of its own)" if e.get("role") else "")
        lines.append(f"| {k} | {where} | {e['measures']} |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(f"experiment_numbering: README has no {BEGIN!r} ... {END!r} block")
        return 1
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + block() + text[stop:]
    if a.check:
        if new != text:
            print("experiment_numbering: README block differs from analysis/paper_experiment_numbers.json")
            return 1
        print("experiment_numbering: README block matches analysis/paper_experiment_numbers.json")
        return 0
    README.write_text(new, encoding="utf-8")
    print("experiment_numbering: README block written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
